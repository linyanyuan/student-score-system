assert.match(source, /TeamOutlined/)
assert.match(source, /ApartmentOutlined/)
assert.match(source, /ReadOutlined/)
assert.match(source, /AlertOutlined/)
assert.ok(source.includes('教师管理工作台'), 'Teacher manage should include workspace title copy')
assert.ok(source.includes('教师总数'), 'Teacher manage should include teacher total metric copy')
assert.ok(source.includes('已绑定班级'), 'Teacher manage should include bound classes metric copy')
assert.ok(source.includes('已分配科目组'), 'Teacher manage should include assignment group metric copy')
assert.ok(source.includes('待补齐项'), 'Teacher manage should include pending metric copy')
assert.ok(source.includes('主流程工作区'), 'Teacher manage should include primary workflow copy')
assert.ok(source.includes('选择教师'), 'Teacher manage should include teacher picker copy')
