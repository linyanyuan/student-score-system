const headerIndex = source.indexOf('教师总数')
const workflowIndex = source.indexOf('主流程工作区')
const matrixIndex = source.indexOf('班级-科目-教师矩阵')
const summaryIndex = source.indexOf('分配汇总')
const teacherSelectIndex = source.indexOf('value={selectedTeacher}')
const bindClassIndex = source.indexOf('value={bindClassIds}')
const selectedClassIndex = source.indexOf('value={selectedClassIds}')
const subjectIndex = source.indexOf('value={selectedSubject}')
assert.ok(headerIndex > -1 && matrixIndex > -1 && headerIndex < matrixIndex, 'Teacher manage should render metrics before matrix section')
assert.ok(workflowIndex > -1 && matrixIndex > -1 && workflowIndex < matrixIndex, 'Teacher manage should render workflow before matrix section')
assert.ok(matrixIndex > -1 && summaryIndex > -1 && matrixIndex < summaryIndex, 'Teacher manage should render matrix before summary section')
assert.ok(teacherSelectIndex > -1 && bindClassIndex > -1 && teacherSelectIndex < bindClassIndex, 'Teacher manage should place bind-class picker after teacher picker')
assert.ok(selectedClassIndex > -1 && subjectIndex > -1 && selectedClassIndex < subjectIndex, 'Teacher manage should place selected-class picker before subject picker')

